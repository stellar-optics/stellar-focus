package capture

// Deterministic generation of standalone replay tests from captured
// fixtures.
//
// A capture records a payload as it was on the chain at capture time. The
// generator turns that record into a _test.go file which, on every later
// run, re-checks the fixture file against the payload that was captured —
// so an edited fixture or a decoder that changed underneath both surface
// as a red test with a field-level diff, instead of drifting quietly.
//
// Generation is deterministic: the same fixture and options always produce
// byte-identical output, with no timestamps and no map iteration, so a
// regenerated test shows up in review as no diff at all.

import (
	"fmt"
	"go/format"
	"go/token"
	"os"
	"path/filepath"
	"strconv"
	"strings"
	"unicode"

	"github.com/stellar-optics/stellar-focus/pkg/golden"
)

// CodegenOptions configures GenerateTest.
type CodegenOptions struct {
	// Package is the package clause of the generated file. It defaults to
	// "fixtures_test", an external test package that can sit next to any
	// package under test.
	Package string
	// FuncName overrides the generated test function name. It must be a
	// valid Go identifier; the default is derived from the fixture name.
	FuncName string
	// FixturePath is the fixture file path as the generated test should
	// reference it — relative to the directory the test will live in.
	// It is required: a replay test that cannot find its fixture would
	// only prove the constant decodes against itself.
	FixturePath string
}

// GenerateTest renders a standalone replay test for one captured fixture.
//
// The returned source is gofmt-formatted and ready to write to a _test.go
// file next to the fixtures it references.
func GenerateTest(name string, f *golden.Fixture, opts CodegenOptions) ([]byte, error) {
	if strings.TrimSpace(name) == "" {
		return nil, fmt.Errorf("generating replay test: fixture name is empty")
	}
	if f == nil {
		return nil, fmt.Errorf("generating replay test for %q: fixture is nil", name)
	}
	if f.XDR == "" {
		return nil, fmt.Errorf("generating replay test for %q: fixture has no XDR payload", name)
	}
	if f.Type == "" {
		return nil, fmt.Errorf("generating replay test for %q: fixture has no XDR type", name)
	}
	if opts.FixturePath == "" {
		return nil, fmt.Errorf("generating replay test for %q: a fixture path is required", name)
	}

	pkg := opts.Package
	if pkg == "" {
		pkg = "fixtures_test"
	}

	ident := exportIdent(name)
	if opts.FuncName != "" {
		if !token.IsIdentifier(opts.FuncName) {
			return nil, fmt.Errorf("generating replay test for %q: %q is not a valid Go identifier",
				name, opts.FuncName)
		}
		ident = opts.FuncName
	}

	constName := ident + "XDR"

	var b strings.Builder
	fmt.Fprintf(&b, "// Code generated by focus capture; DO NOT EDIT.\n")
	fmt.Fprintf(&b, "//\n")
	fmt.Fprintf(&b, "// Replay of the %s captured as %q", f.Type, name)
	if f.Description != "" {
		fmt.Fprintf(&b, ": %s", f.Description)
	}
	fmt.Fprintf(&b, ".\n\n")
	fmt.Fprintf(&b, "package %s\n\n", pkg)
	fmt.Fprintf(&b, "import (\n")
	fmt.Fprintf(&b, "\t\"testing\"\n\n")
	fmt.Fprintf(&b, "\t\"github.com/stellar-optics/stellar-focus/pkg/focus\"\n")
	fmt.Fprintf(&b, "\t\"github.com/stellar-optics/stellar-focus/pkg/golden\"\n")
	fmt.Fprintf(&b, ")\n\n")
	fmt.Fprintf(&b, "// %s is the payload as it was captured from the chain.\n", constName)
	fmt.Fprintf(&b, "const %s = %s\n\n", constName, quote(f.XDR))
	fmt.Fprintf(&b, "// %s checks the stored fixture against the captured payload.\n", ident)
	fmt.Fprintf(&b, "//\n")
	fmt.Fprintf(&b, "// A failure here means one of two things: the fixture file was edited\n")
	fmt.Fprintf(&b, "// without re-capturing, or a decoder changed underneath it. Either way\n")
	fmt.Fprintf(&b, "// the diff names the field.\n")
	fmt.Fprintf(&b, "func %s(t *testing.T) {\n", ident)
	fmt.Fprintf(&b, "\tf, err := golden.Load(%s)\n", quote(filepath.ToSlash(opts.FixturePath)))
	fmt.Fprintf(&b, "\tif err != nil {\n")
	fmt.Fprintf(&b, "\t\tt.Fatalf(\"loading fixture: %%v\", err)\n")
	fmt.Fprintf(&b, "\t}\n")
	fmt.Fprintf(&b, "\tfocus.AssertEqualAs(t, %s, %s, f.XDR)\n", quote(f.Type), constName)
	fmt.Fprintf(&b, "}\n")

	src, err := format.Source([]byte(b.String()))
	if err != nil {
		return nil, fmt.Errorf("formatting generated test for %q: %w", name, err)
	}
	return src, nil
}

// GenerateTestFile loads a fixture and writes its replay test to outPath.
//
// The generated file references the fixture by its own path relative to the
// generated file's directory, so moving or renaming the pair must move or
// rename both — which is exactly what regenerating does.
func GenerateTestFile(fixturePath, outPath string, opts CodegenOptions) error {
	f, err := golden.Load(fixturePath)
	if err != nil {
		return fmt.Errorf("loading fixture %s: %w", fixturePath, err)
	}

	if opts.FixturePath == "" {
		rel, relErr := filepath.Rel(filepath.Dir(outPath), fixturePath)
		if relErr != nil {
			return fmt.Errorf("relating %s to %s: %w", fixturePath, filepath.Dir(outPath), relErr)
		}
		opts.FixturePath = rel
	}

	name := strings.TrimSuffix(filepath.Base(fixturePath), filepath.Ext(fixturePath))
	name = strings.TrimSuffix(name, ".golden")

	src, err := GenerateTest(name, f, opts)
	if err != nil {
		return err
	}
	if err := writeFileNew(outPath, src); err != nil {
		return fmt.Errorf("writing generated test %s: %w", outPath, err)
	}
	return nil
}

// writeFileNew writes data to path, creating parent directories.
func writeFileNew(path string, data []byte) error {
	if dir := filepath.Dir(path); dir != "" && dir != "." {
		if err := os.MkdirAll(dir, 0o755); err != nil {
			return fmt.Errorf("creating %s: %w", dir, err)
		}
	}
	if err := os.WriteFile(path, data, 0o644); err != nil {
		return err
	}
	return nil
}

// exportIdent turns an arbitrary fixture name into an exported Go
// identifier: words are camel-cased, punctuation becomes a word break, and
// anything that would start with a digit is prefixed so the result is
// always usable as a Test… function name.
func exportIdent(name string) string {
	var b strings.Builder
	upperNext := true
	for _, r := range name {
		switch {
		case unicode.IsLetter(r) || unicode.IsDigit(r):
			if upperNext {
				b.WriteRune(unicode.ToUpper(r))
				upperNext = false
			} else {
				b.WriteRune(r)
			}
		default:
			upperNext = true
		}
	}
	out := b.String()
	if out == "" {
		return "TestReplay"
	}
	if unicode.IsDigit(rune(out[0])) {
		out = "T" + out
	}
	return "Test" + out + "Replay"
}

// quote renders s as a Go string literal.
func quote(s string) string {
	return strconv.Quote(s)
}
