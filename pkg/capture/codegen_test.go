func TestGenerateTestFileDerivesEverything(t *testing.T) {
	t.Parallel()

	dir := t.TempDir()
	fixturePath := filepath.Join(dir, "envelope.golden.json")
	if err := golden.Save(fixturePath, parsedFixture(t)); err != nil {
		t.Fatalf("saving fixture: %v", err)
	}

	outPath := filepath.Join(dir, "envelope_replay_test.go")
	if err := capture.GenerateTestFile(fixturePath, outPath, capture.CodegenOptions{}); err != nil {
		t.Fatalf("GenerateTestFile: %v", err)
	}

	data, err := os.ReadFile(outPath)
	if err != nil {
		t.Fatalf("reading generated file: %v", err)
	}
	parseGenerated(t, data)

	out := string(data)
	// The generated test lives next to the fixture, so it must reference
	// it by bare filename.
	if !strings.Contains(out, `golden.Load("envelope.golden.json")`) {
		t.Errorf("generated test does not reference the fixture relatively:\n%s", out)
	}
	if !strings.Contains(out, "func TestEnvelopeReplay(") {
		t.Errorf("function name not derived from the filename:\n%s", out)
	}
}

