// parsedFixture builds a fixture the way Capture does, from the captured
// testdata payloads.
func parsedFixture(t *testing.T) *golden.Fixture {
	t.Helper()
	f, err := golden.Build(envelopeXDR(t), "TransactionEnvelope", "a failed payment", nil)
	if err != nil {
		t.Fatalf("golden.Build: %v", err)
	}
	return f
}

func parseGenerated(t *testing.T, src []byte) {
	t.Helper()
	if _, err := parser.ParseFile(token.NewFileSet(), "generated.go", src, parser.AllErrors); err != nil {
		t.Fatalf("generated source does not parse: %v\n%s", err, src)
	}
}

func TestGenerateReplayTestProducesTableDrivenSource(t *testing.T) {
	t.Parallel()

	src, err := capture.GenerateReplayTest(&capture.CaptureFixture{
		Name:        "failed payment",
		Fixture:     parsedFixture(t),
		FixturePath: "testdata/failed_payment.golden.json",
	})
	if err != nil {
		t.Fatalf("GenerateReplayTest: %v", err)
	}
	parseGenerated(t, []byte(src))

	for _, want := range []string{
		"package fixtures_test",
		"func TestReplay_FailedPayment(t *testing.T)",
		"tests := []struct {",
		`golden.Load("testdata/failed_payment.golden.json")`,
		"focus.AssertEnvelopeEqual(t, capturedXDR, tt.xdr)",
		"focus.AssertOperationTypes(t, tt.xdr, wantOps...)",
		"wantOps := []string{",
		"// Code generated by focus capture; DO NOT EDIT.",
	} {
		if !strings.Contains(src, want) {
			t.Errorf("generated replay test is missing %q:\n%s", want, src)
		}
	}
}

