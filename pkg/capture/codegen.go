package capture

// Deterministic generation of standalone replay tests from captured
// fixtures.
//
// A capture records a payload as it was on the chain at capture time. The
// generator turns that record into a _test.go file which, on every later
// run, re-checks the fixture file against the payload that was captured —
// so an edited fixture or a decoder that changed underneath both surface
// as a red test with a field-level diff, instead of drifting quietly.
//
// Generation is deterministic: the same fixture and options always produce
// byte-identical output, with no timestamps and no map iteration, so a
// regenerated test shows up in review as no diff at all.

import (
	"fmt"
	"go/format"
	"go/token"
	"os"
	"path/filepath"
	"strconv"
	"strings"
	"unicode"

	"github.com/stellar-optics/stellar-xdr-lens/pkg/lens"

	"github.com/stellar-optics/stellar-focus/pkg/golden"
)

// CaptureFixture is one captured fixture as the replay generator sees it.
//
// It pairs the fixture itself with the two pieces of context a generated test
// needs: the name that becomes the test function, and the path the generated
// file should load the fixture from. Keeping them together means the call site
// does not have to repeat the fixture's contents in its own arguments.
//
//nolint:revive // The public name is fixed by issue #240.
type CaptureFixture struct {
	// Name identifies the fixture and becomes TestReplay_<Name>. When empty it
	// is derived from FixturePath, then from the fixture type.
	Name string
	// Fixture is the captured golden fixture.
	Fixture *golden.Fixture
	// FixturePath is how the generated test should reference the fixture,
	// relative to the directory the generated file lives in.
	FixturePath string
	// Package is the package clause of the generated file. Empty uses
	// "fixtures_test".
	Package string
}

// GenerateReplayTest renders a compile-ready, table-driven replay test for one
// captured transaction envelope.
//
// The generated file loads the stored fixture, compares it against the XDR that
// was captured, and asserts the operation types that were captured. Running it
// therefore detects both an edited fixture and a decoder that changed under a
// fixture, and reports the differing field through focus's normal diff.
//
// Output is deterministic and gofmt-formatted, so regenerating an unchanged
// fixture produces no diff.
func GenerateReplayTest(fixture *CaptureFixture) (string, error) {
	if fixture == nil {
		return "", fmt.Errorf("generating replay test: capture fixture is nil")
	}
	if fixture.Fixture == nil {
		return "", fmt.Errorf("generating replay test: fixture is nil")
	}
	f := fixture.Fixture
	if f.XDR == "" {
		return "", fmt.Errorf("generating replay test: fixture has no XDR payload")
	}
	if f.Type != "TransactionEnvelope" {
		return "", fmt.Errorf("generating replay test: fixture type is %q, want TransactionEnvelope", f.Type)
	}
	if fixture.FixturePath == "" {
		return "", fmt.Errorf("generating replay test: a fixture path is required")
	}

	operations, err := replayOperationTypes(f)
	if err != nil {
		return "", err
	}

	name := fixture.Name
	if name == "" {
		name = fixtureNameFromPath(fixture.FixturePath)
	}
	if name == "" {
		return "", fmt.Errorf("generating replay test: fixture name is empty")
	}

	pkg := fixture.Package
	if pkg == "" {
		pkg = "fixtures_test"
	}
	if !token.IsIdentifier(pkg) {
		return "", fmt.Errorf("generating replay test: %q is not a valid package name", pkg)
	}

	ident := "TestReplay_" + pascalIdent(name)
	opNames := make([]string, len(operations))
	for i, op := range operations {
		opNames[i] = quote(op)
	}

	var b strings.Builder
	fmt.Fprintf(&b, "// Code generated by focus capture; DO NOT EDIT.\n")
	fmt.Fprintf(&b, "//\n")
	fmt.Fprintf(&b, "// Replay of the %s captured as %q.\n\n", f.Type, name)
	fmt.Fprintf(&b, "package %s\n\n", pkg)
	fmt.Fprintf(&b, "import (\n")
	fmt.Fprintf(&b, "\t\"testing\"\n\n")
	fmt.Fprintf(&b, "\t\"github.com/stellar-optics/stellar-focus/pkg/focus\"\n")
	fmt.Fprintf(&b, "\t\"github.com/stellar-optics/stellar-focus/pkg/golden\"\n")
	fmt.Fprintf(&b, ")\n\n")
	fmt.Fprintf(&b, "// %s replays the captured transaction and checks that the stored\n", ident)
	fmt.Fprintf(&b, "// fixture still matches it.\n")
	fmt.Fprintf(&b, "func %s(t *testing.T) {\n", ident)
	fmt.Fprintf(&b, "\tconst capturedXDR = %s\n\n", quote(f.XDR))
	fmt.Fprintf(&b, "\tfixture, err := golden.Load(%s)\n", quote(filepath.ToSlash(fixture.FixturePath)))
	fmt.Fprintf(&b, "\tif err != nil {\n")
	fmt.Fprintf(&b, "\t\tt.Fatalf(\"loading fixture: %%v\", err)\n")
	fmt.Fprintf(&b, "\t}\n\n")
	fmt.Fprintf(&b, "\twantOps := []string{%s}\n\n", strings.Join(opNames, ", "))
	fmt.Fprintf(&b, "\ttests := []struct {\n")
	fmt.Fprintf(&b, "\t\tname string\n")
	fmt.Fprintf(&b, "\t\txdr  string\n")
	fmt.Fprintf(&b, "\t}{\n")
	fmt.Fprintf(&b, "\t\t{name: \"captured\", xdr: capturedXDR},\n")
	fmt.Fprintf(&b, "\t\t{name: \"fixture\", xdr: fixture.XDR},\n")
	fmt.Fprintf(&b, "\t}\n")
	fmt.Fprintf(&b, "\tfor _, tt := range tests {\n")
	fmt.Fprintf(&b, "\t\tt.Run(tt.name, func(t *testing.T) {\n")
	fmt.Fprintf(&b, "\t\t\tfocus.AssertEnvelopeEqual(t, capturedXDR, tt.xdr)\n")
	fmt.Fprintf(&b, "\t\t\tfocus.AssertOperationTypes(t, tt.xdr, wantOps...)\n")
	fmt.Fprintf(&b, "\t\t})\n")
	fmt.Fprintf(&b, "\t}\n")
	fmt.Fprintf(&b, "}\n")

	src, err := format.Source([]byte(b.String()))
	if err != nil {
		return "", fmt.Errorf("formatting generated replay test for %q: %w", name, err)
	}
	return string(src), nil
}

// replayOperationTypes reads the snake_case operation names out of the
// captured envelope, using the same summary lens produces for AssertOperationTypes.
func replayOperationTypes(f *golden.Fixture) ([]string, error) {
	decoded, err := lens.DecodeAs(f.XDR, "TransactionEnvelope")
	if err != nil {
		return nil, fmt.Errorf("decoding captured envelope for replay: %w", err)
	}
	summary, err := lens.Explain(decoded)
	if err != nil {
		return nil, fmt.Errorf("summarising captured envelope for replay: %w", err)
	}
	operations := make([]string, len(summary.Operations))
	for i, op := range summary.Operations {
		operations[i] = op.Type
	}
	return operations, nil
}

// fixtureNameFromPath derives a fixture name from its filename, dropping the
// golden suffix so "payment.golden.json" becomes "payment".
func fixtureNameFromPath(path string) string {
	name := filepath.Base(path)
	for _, suffix := range []string{".golden.json.gz", ".golden.yaml", ".golden.txt", ".golden.json"} {
		if strings.HasSuffix(name, suffix) {
			return strings.TrimSuffix(name, suffix)
		}
	}
	return strings.TrimSuffix(name, filepath.Ext(name))
}

// pascalIdent turns a fixture name into an exported identifier fragment:
// punctuation becomes a word break, words are camel-cased, and a leading digit
// is prefixed so the result is always a valid Go identifier.
func pascalIdent(name string) string {
	var b strings.Builder
	upperNext := true
	for _, r := range name {
		switch {
		case unicode.IsLetter(r) || unicode.IsDigit(r):
			if upperNext {
				b.WriteRune(unicode.ToUpper(r))
				upperNext = false
			} else {
				b.WriteRune(r)
			}
		default:
			upperNext = true
		}
	}
	out := b.String()
	if out == "" {
		return "Fixture"
	}
	if unicode.IsDigit(rune(out[0])) {
		out = "T" + out
	}
	return out
}

// CodegenOptions configures GenerateTest.
type CodegenOptions struct {
	// Package is the package clause of the generated file. It defaults to
	// "fixtures_test", an external test package that can sit next to any
	// package under test.
	Package string
	// FuncName overrides the generated test function name. It must be a
	// valid Go identifier; the default is derived from the fixture name.
	FuncName string
	// FixturePath is the fixture file path as the generated test should
	// reference it — relative to the directory the test will live in.
	// It is required: a replay test that cannot find its fixture would
	// only prove the constant decodes against itself.
	FixturePath string
}

// GenerateTest renders a standalone replay test for one captured fixture.
//
// The returned source is gofmt-formatted and ready to write to a _test.go
// file next to the fixtures it references.
func GenerateTest(name string, f *golden.Fixture, opts CodegenOptions) ([]byte, error) {
	if strings.TrimSpace(name) == "" {
		return nil, fmt.Errorf("generating replay test: fixture name is empty")
	}
	if f == nil {
		return nil, fmt.Errorf("generating replay test for %q: fixture is nil", name)
	}
	if f.XDR == "" {
		return nil, fmt.Errorf("generating replay test for %q: fixture has no XDR payload", name)
	}
	if f.Type == "" {
		return nil, fmt.Errorf("generating replay test for %q: fixture has no XDR type", name)
	}
	if opts.FixturePath == "" {
		return nil, fmt.Errorf("generating replay test for %q: a fixture path is required", name)
	}

	pkg := opts.Package
	if pkg == "" {
		pkg = "fixtures_test"
	}

	ident := exportIdent(name)
	if opts.FuncName != "" {
		if !token.IsIdentifier(opts.FuncName) {
			return nil, fmt.Errorf("generating replay test for %q: %q is not a valid Go identifier",
				name, opts.FuncName)
		}
		ident = opts.FuncName
	}

	constName := ident + "XDR"

	var b strings.Builder
	fmt.Fprintf(&b, "// Code generated by focus capture; DO NOT EDIT.\n")
	fmt.Fprintf(&b, "//\n")
	fmt.Fprintf(&b, "// Replay of the %s captured as %q", f.Type, name)
	if f.Description != "" {
		fmt.Fprintf(&b, ": %s", f.Description)
	}
	fmt.Fprintf(&b, ".\n\n")
	fmt.Fprintf(&b, "package %s\n\n", pkg)
	fmt.Fprintf(&b, "import (\n")
	fmt.Fprintf(&b, "\t\"testing\"\n\n")
	fmt.Fprintf(&b, "\t\"github.com/stellar-optics/stellar-focus/pkg/focus\"\n")
	fmt.Fprintf(&b, "\t\"github.com/stellar-optics/stellar-focus/pkg/golden\"\n")
	fmt.Fprintf(&b, ")\n\n")
	fmt.Fprintf(&b, "// %s is the payload as it was captured from the chain.\n", constName)
	fmt.Fprintf(&b, "const %s = %s\n\n", constName, quote(f.XDR))
	fmt.Fprintf(&b, "// %s checks the stored fixture against the captured payload.\n", ident)
	fmt.Fprintf(&b, "//\n")
	fmt.Fprintf(&b, "// A failure here means one of two things: the fixture file was edited\n")
	fmt.Fprintf(&b, "// without re-capturing, or a decoder changed underneath it. Either way\n")
	fmt.Fprintf(&b, "// the diff names the field.\n")
	fmt.Fprintf(&b, "func %s(t *testing.T) {\n", ident)
	fmt.Fprintf(&b, "\tf, err := golden.Load(%s)\n", quote(filepath.ToSlash(opts.FixturePath)))
	fmt.Fprintf(&b, "\tif err != nil {\n")
	fmt.Fprintf(&b, "\t\tt.Fatalf(\"loading fixture: %%v\", err)\n")
	fmt.Fprintf(&b, "\t}\n")
	fmt.Fprintf(&b, "\tfocus.AssertEqualAs(t, %s, %s, f.XDR)\n", quote(f.Type), constName)
	fmt.Fprintf(&b, "}\n")

	src, err := format.Source([]byte(b.String()))
	if err != nil {
		return nil, fmt.Errorf("formatting generated test for %q: %w", name, err)
	}
	return src, nil
}

// GenerateTestFile loads a fixture and writes its replay test to outPath.
//
// The generated file references the fixture by its own path relative to the
// generated file's directory, so moving or renaming the pair must move or
// rename both — which is exactly what regenerating does.
func GenerateTestFile(fixturePath, outPath string, opts CodegenOptions) error {
	f, err := golden.Load(fixturePath)
	if err != nil {
		return fmt.Errorf("loading fixture %s: %w", fixturePath, err)
	}

	if opts.FixturePath == "" {
		rel, relErr := filepath.Rel(filepath.Dir(outPath), fixturePath)
		if relErr != nil {
			return fmt.Errorf("relating %s to %s: %w", fixturePath, filepath.Dir(outPath), relErr)
		}
		opts.FixturePath = rel
	}

	name := strings.TrimSuffix(filepath.Base(fixturePath), filepath.Ext(fixturePath))
	name = strings.TrimSuffix(name, ".golden")

	src, err := GenerateTest(name, f, opts)
	if err != nil {
		return err
	}
	if err := writeFileNew(outPath, src); err != nil {
		return fmt.Errorf("writing generated test %s: %w", outPath, err)
	}
	return nil
}

// writeFileNew writes data to path, creating parent directories.
func writeFileNew(path string, data []byte) error {
	if dir := filepath.Dir(path); dir != "" && dir != "." {
		if err := os.MkdirAll(dir, 0o755); err != nil {
			return fmt.Errorf("creating %s: %w", dir, err)
		}
	}
	if err := os.WriteFile(path, data, 0o644); err != nil {
		return err
	}
	return nil
}

// exportIdent turns an arbitrary fixture name into an exported Go
// identifier: words are camel-cased, punctuation becomes a word break, and
// anything that would start with a digit is prefixed so the result is
// always usable as a Test… function name.
func exportIdent(name string) string {
	return "Test" + pascalIdent(name) + "Replay"
}

// quote renders s as a Go string literal.
func quote(s string) string {
	return strconv.Quote(s)
}
