func TestWriteReplayTestsBatch(t *testing.T) {
	t.Parallel()

	dir := t.TempDir()
	fixturePath := filepath.Join(dir, "envelope.golden.json")
	if err := golden.Save(fixturePath, parsedFixture(t)); err != nil {
		t.Fatalf("saving fixture: %v", err)
	}

	outDir := filepath.Join(dir, "generated")
	paths, err := capture.WriteReplayTests([]*capture.CaptureFixture{
		{Name: "envelope", Fixture: parsedFixture(t), FixturePath: fixturePath},
	}, outDir)
	if err != nil {
		t.Fatalf("WriteReplayTests: %v", err)
	}
	if len(paths) != 1 {
		t.Fatalf("want one generated file, got %v", paths)
	}

	data, err := os.ReadFile(paths[0])
	if err != nil {
		t.Fatalf("reading generated file: %v", err)
	}
	parseGenerated(t, data)
	if !strings.Contains(string(data), `golden.Load("../envelope.golden.json")`) {
		t.Errorf("generated test does not reference the fixture relatively:\n%s", data)
	}
}

func TestGeneratedReplayTestCompilesAndPasses(t *testing.T) {
	t.Parallel()

	dir, err := os.MkdirTemp(".", "codegen-compile-")
	if err != nil {
		t.Fatalf("creating temp package: %v", err)
	}
	defer os.RemoveAll(dir)

	fixturePath := filepath.Join(dir, "envelope.golden.json")
	if err := golden.Save(fixturePath, parsedFixture(t)); err != nil {
		t.Fatalf("saving fixture: %v", err)
	}

	src, err := capture.GenerateReplayTest(&capture.CaptureFixture{
		Name:        "envelope",
		Fixture:     parsedFixture(t),
		FixturePath: "envelope.golden.json",
		Package:     "fixtures",
	})
	if err != nil {
		t.Fatalf("GenerateReplayTest: %v", err)
	}
	if err := os.WriteFile(filepath.Join(dir, "replay_test.go"), []byte(src), 0o644); err != nil {
		t.Fatalf("writing generated test: %v", err)
	}

	cmd := exec.Command("go", "test", "./"+filepath.Base(dir), "-run", "^TestReplay_Envelope$", "-count=1")
	output, err := cmd.CombinedOutput()
	if err != nil {
		t.Fatalf("generated test did not compile or pass: %v\n%s\n--- source ---\n%s", err, output, src)
	}
}

