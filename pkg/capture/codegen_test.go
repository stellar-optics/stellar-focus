// parsedFixture builds a fixture the way Capture does, from the captured
// testdata payloads.
func parsedFixture(t *testing.T) *golden.Fixture {
	t.Helper()
	f, err := golden.Build(envelopeXDR(t), "TransactionEnvelope", "a failed payment", nil)
	if err != nil {
		t.Fatalf("golden.Build: %v", err)
	}
	return f
}

func parseGenerated(t *testing.T, src []byte) {
	t.Helper()
	if _, err := parser.ParseFile(token.NewFileSet(), "generated.go", src, parser.AllErrors); err != nil {
		t.Fatalf("generated source does not parse: %v\n%s", err, src)
	}
}

func TestGenerateTestProducesAValidReplay(t *testing.T) {
	t.Parallel()

	src, err := capture.GenerateTest("failed_payment", parsedFixture(t), capture.CodegenOptions{
		FixturePath: "testdata/failed_payment.golden.json",
	})
	if err != nil {
		t.Fatalf("GenerateTest: %v", err)
	}
	parseGenerated(t, src)

	out := string(src)
	for _, want := range []string{
		"package fixtures_test",
		`golden.Load("testdata/failed_payment.golden.json")`,
		`focus.AssertEqualAs(t, "TransactionEnvelope"`,
		"func TestFailedPaymentReplay(t *testing.T)",
		"// Code generated by focus capture; DO NOT EDIT.",
	} {
		if !strings.Contains(out, want) {
			t.Errorf("generated test is missing %q:\n%s", want, out)
		}
	}
}

func TestGenerateTestIsDeterministic(t *testing.T) {
	t.Parallel()

	opts := capture.CodegenOptions{FixturePath: "testdata/x.golden.json"}
	first, err := capture.GenerateTest("envelope", parsedFixture(t), opts)
	if err != nil {
		t.Fatalf("GenerateTest: %v", err)
	}
	second, err := capture.GenerateTest("envelope", parsedFixture(t), opts)
	if err != nil {
		t.Fatalf("GenerateTest (second run): %v", err)
	}
	if string(first) != string(second) {
		t.Errorf("generation is not deterministic:\n--- first ---\n%s\n--- second ---\n%s", first, second)
	}
}

func TestGenerateTestHonoursOptions(t *testing.T) {
	t.Parallel()

	src, err := capture.GenerateTest("envelope", parsedFixture(t), capture.CodegenOptions{
		Package:     "myfixtures",
		FuncName:    "TestTheCapturedEnvelope",
		FixturePath: "../fixtures/envelope.golden.json",
	})
	if err != nil {
		t.Fatalf("GenerateTest: %v", err)
	}
	parseGenerated(t, src)

	out := string(src)
	if !strings.Contains(out, "package myfixtures") {
		t.Errorf("package clause not honoured:\n%s", out)
	}
	if !strings.Contains(out, "func TestTheCapturedEnvelope(") {
		t.Errorf("function name not honoured:\n%s", out)
	}
}

